/* ============================================================
   朝代与「时代组」
   ----------------------------------------------------------
   数据里的 dynasty 是**具体朝代**（先秦 / 汉 / 魏晋 / 南北朝 / 唐 / 宋），
   界面上的筛选按钮却是**时代组**——「先唐」一个按钮就管住前四个。
   中间这一层映射只写在这里，界面与筛选逻辑都只认时代组的键，
   于是以后再加元、明、清，只需要在 ERAS 里补一行。

   为什么不让界面直接列四个朝代按钮：筛选条只有 400 多像素，
   四个小朝代并排会把「唐诗 / 宋词」这两个主角挤没。
   ============================================================ */

/** 具体朝代 → 时代组 */
export const ERA_OF = {
  先秦: "先唐",
  汉: "先唐",
  魏晋: "先唐",
  南北朝: "先唐",
  唐: "唐",
  宋: "宋",
};

/** 时代组 → 具体朝代（顺序即竖排/列表里的先后） */
export const DYNASTIES_OF = {
  先唐: ["先秦", "汉", "魏晋", "南北朝"],
  唐: ["唐"],
  宋: ["宋"],
};

/** 筛选条与篇目栏页签共用的顺序 */
export const ERAS = [
  { val: "全部", label: "全部" },
  { val: "先唐", label: "先唐" },
  { val: "唐", label: "唐诗" },
  { val: "宋", label: "宋词" },
];

/** 具体朝代属于哪个时代组（未知朝代自成一档，不会漏掉） */
export function eraOf(dynasty) {
  return ERA_OF[dynasty] || dynasty;
}

/** 该诗是否落在选中的时代组里 */
export function inEra(dynasty, era) {
  return era === "全部" || eraOf(dynasty) === era;
}

/** 按「先唐 → 唐 → 宋」的真实时间顺序给朝代排序（用于竖排落款等） */
const ORDER = { 先秦: 0, 汉: 1, 魏晋: 2, 南北朝: 3, 唐: 4, 宋: 5 };
export function dynastyOrder(dynasty) {
  return ORDER[dynasty] === undefined ? 99 : ORDER[dynasty];
}
